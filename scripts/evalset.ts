// Builds api/_data/evalset.js: the agent's real exam, generated from the synthetic scenarios.
// Each scenario gives a practice set (the agent sees its mistakes and the right answers), a validation set
// (only scores come back: the harness compares before and after on it) and a sealed held-out set.
// The answers stay on the server. Run `pnpm evalset` to rebuild, `pnpm evalset --verify` to check.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { SCENARIOS, generateScenarioDataset, scenarioIndex, type ScenarioDefinition } from "@skillab/scenarios";
import type { Split } from "@skillab/contracts";

/** The scenarios whose answer is one label per item (conciliación also names a target row). */
export const AGENT_SCENARIOS = ["manufactura", "devoluciones", "mensajes", "envios"] as const;
const COUNTS: Record<Split, number> = { adaptation: 4, validation: 6, test: 4 };

function setOf(def: ScenarioDefinition, split: Split) {
  const ds = generateScenarioDataset(def, scenarioIndex(def.id), "interleaved", split, COUNTS[split]);
  return ds.cases.map((c) => {
    const byId = new Map(c.truth.map((t) => [t.itemId, t.label]));
    return {
      context: c.batch.context,
      items: c.batch.items.map((it) => ({ id: it.itemId, fields: it.fields })),
      truth: c.batch.items.map((it) => byId.get(it.itemId) ?? ""),
    };
  });
}

export function buildEvalset() {
  const scenarios: Record<string, unknown> = {};
  for (const id of AGENT_SCENARIOS) {
    const def = SCENARIOS.find((s) => s.id === id);
    if (!def) throw new Error(`missing scenario ${id}`);
    const { info } = def;
    scenarios[id] = {
      id,
      version: def.version,
      industry: info.industry,
      title: info.title,
      task: info.task,
      labels: info.labels,
      // context names only: each context's rule is what the agent has to learn
      contexts: [info.contexts.A, info.contexts.B].map((c) => ({ id: c.id, name: c.name })),
      sets: { practice: setOf(def, "adaptation"), validation: setOf(def, "validation"), sealed: setOf(def, "test") },
    };
  }
  return { version: "evalset@1", scenarios };
}

export function renderEvalset(): string {
  return (
    "// Generated by scripts/evalset.ts from packages/scenarios. Do not edit: run `pnpm evalset`.\n" +
    "// The answers (truth) never leave the server.\n" +
    `export const EVALSET = ${JSON.stringify(buildEvalset())};\n`
  );
}

export const EVALSET_PATH = fileURLToPath(new URL("../api/_data/evalset.js", import.meta.url));

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = renderEvalset();
  if (process.argv.includes("--verify")) {
    const now = readFileSync(EVALSET_PATH, "utf8");
    if (now !== next) {
      console.error("api/_data/evalset.js is stale: run `pnpm evalset`");
      process.exit(1);
    }
    console.log("evalset ok");
  } else {
    writeFileSync(EVALSET_PATH, next);
    console.log(`wrote ${EVALSET_PATH} (${(next.length / 1024).toFixed(0)} KB)`);
  }
}
